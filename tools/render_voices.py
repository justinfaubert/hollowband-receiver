#!/usr/bin/env python3
"""Render every line the radio can say into voice audio, packed one file per segment.

    pip install piper-tts            (and have ffmpeg on the path)
    node tools/dump_lines.js > /tmp/lines.json
    python3 tools/render_voices.py /tmp/lines.json /path/to/piper/voices

Writes audio/voices/*.mp3 and js/voices.js. Voice casting is in tools/cast.json.
To use other voices (your own recordings, another TTS, Suno), produce the same
files: one mp3 per sprite name, and a js/voices.js that says where each line starts.
"""
import io, json, os, subprocess, sys, tempfile, wave
from piper import PiperVoice, SynthesisConfig

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SR, GAP = 22050, 0.3

def main(lines_path, voices_dir):
    lines = json.load(open(lines_path))
    cast = json.load(open(os.path.join(ROOT, "tools", "cast.json")))
    out_dir = os.path.join(ROOT, "audio", "voices")
    os.makedirs(out_dir, exist_ok=True)
    tmp = tempfile.mkdtemp()
    models, clips = {}, {}
    for n, ln in enumerate(lines):
        c = cast[ln["cast"]]
        if c["model"] not in models:
            models[c["model"]] = PiperVoice.load(os.path.join(voices_dir, c["model"] + ".onnx"))
        v = models[c["model"]]
        cfg = SynthesisConfig(speaker_id=c.get("speaker"), length_scale=c.get("len"),
                              noise_scale=c.get("noise"), noise_w_scale=c.get("noisew"))
        raw = os.path.join(tmp, "raw.wav")
        with wave.open(raw, "wb") as w:
            v.synthesize_wav(ln["text"], w, syn_config=cfg)
        p = c.get("pitch", 1.0)
        af = []
        if p != 1.0:
            af += ["asetrate=%d" % round(v.config.sample_rate * p), "atempo=%.4f" % (1 / p)]
        af += ["aresample=%d" % SR, "highpass=f=70",
               "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.02",
               "areverse", "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.05", "areverse",
               "dynaudnorm=f=200:g=15:p=0.7"]
        wav = os.path.join(tmp, "%s_%s.wav" % (ln["sprite"], ln["key"]))
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", raw, "-af", ",".join(af), "-ac", "1", "-ar", str(SR),
                        "-sample_fmt", "s16", wav], check=True)
        clips.setdefault(ln["sprite"], []).append((ln["key"], wav))
        if n % 25 == 0:
            print("%d/%d %s" % (n, len(lines), ln["sprite"]), flush=True)
    manifest = {}
    for sprite, items in sorted(clips.items()):
        joined = os.path.join(tmp, "joined.wav")
        table, t = {}, 0.0
        with wave.open(joined, "wb") as out:
            out.setnchannels(1); out.setsampwidth(2); out.setframerate(SR)
            for key, wav in items:
                with wave.open(wav) as w:
                    frames = w.readframes(w.getnframes()); dur = w.getnframes() / SR
                out.writeframes(frames)
                out.writeframes(b"\0\0" * int(SR * GAP))
                table[key] = [round(max(0, t - 0.03), 3), round(dur + 0.12, 3)]
                t += dur + GAP
        mp3 = os.path.join(out_dir, sprite + ".mp3")
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", joined, "-c:a", "libmp3lame", "-b:a", "40k", "-ac", "1", mp3], check=True)
        manifest[sprite] = {"file": "audio/voices/" + sprite + ".mp3", "clips": table}
    with open(os.path.join(ROOT, "js", "voices.js"), "w") as f:
        f.write("/* generated by tools/render_voices.py — where each spoken line starts, in seconds */\n")
        f.write("window.HB_VOICES=" + json.dumps({"sprites": manifest}, separators=(",", ":")) + ";\n")
    total = sum(os.path.getsize(os.path.join(out_dir, x)) for x in os.listdir(out_dir))
    print("done: %d sprites, %.1f MB" % (len(manifest), total / 1e6), flush=True)

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
