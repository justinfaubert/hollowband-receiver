#!/usr/bin/env python3
"""Put your own music on the dial.

Drop audio files (mp3, ogg, wav, m4a, flac, opus) into tracks/ and run:

    python3 tools/add_tracks.py

It rewrites js/tracks.js. Your station appears on the dial the next time the page loads,
on whatever frequency you first claim by adding a track or going on air.
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXT = (".mp3", ".ogg", ".wav", ".m4a", ".flac", ".opus", ".aac")
files = sorted(f for f in os.listdir(os.path.join(ROOT, "tracks")) if f.lower().endswith(EXT))
tracks = [{"title": os.path.splitext(f)[0].replace("_", " "), "file": "tracks/" + f} for f in files]
with open(os.path.join(ROOT, "js", "tracks.js"), "w") as out:
    out.write("/* Your own tracks, bundled with the project. Generated by tools/add_tracks.py from the tracks/ folder. */\n")
    out.write("window.HB_TRACKS=" + json.dumps(tracks, indent=1) + ";\n")
print("%d track(s) on your station" % len(tracks))
